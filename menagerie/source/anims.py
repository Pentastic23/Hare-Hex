"""Combat animation clips for the voxel units.

Rotations are Euler degrees in glTF axes (X right, Y up, Z forward), applied X->Y->Z.
  - arm or leg swing forward:  negative X
  - lean the body back:        negative X;  lean forward: positive X
  - arm_r (character's right, -X side) out sideways: negative Z;  arm_l out: positive Z
  - dragon wing_r flap down:   positive Z;  wing_l flap down: negative Z
Translations are offsets in meters at 1x scale (scaled with the tier automatically).

Clip names (same on every unit, so one animator controller fits all):
  idle, walk, attack, skill, hit, death, victory
"""

Z3 = (0, 0, 0)


class Clip:
    def __init__(self, dur, loop=True):
        self.dur = dur
        self.loop = loop
        self.tracks = {}

    def r(self, bone, *keys):
        self.tracks.setdefault(bone, {})['r'] = list(keys)
        return self

    def t(self, bone, *keys):
        self.tracks.setdefault(bone, {})['t'] = list(keys)
        return self

    def out(self, bones):
        tracks = {b: {k: sorted(keys, key=lambda kk: kk[0]) for k, keys in v.items()}
                  for b, v in self.tracks.items() if b in bones}
        for b, v in tracks.items():
            for k, keys in v.items():
                ts = [kk[0] for kk in keys]
                assert len(set(ts)) == len(ts) and 0 <= ts[0] and ts[-1] <= self.dur + 1e-9, (b, k, ts)
        if 'aura' in bones:
            n = 8
            tracks['aura'] = {'r': [(self.dur * i / n, (0, 360.0 * i / n, 0)) for i in range(n + 1)],
                              't': [(0, Z3), (self.dur / 2, (0, 0.04, 0)), (self.dur, Z3)]}
        return {'dur': self.dur, 'loop': self.loop, 'tracks': tracks}


def mirror_arm(keys):
    """Mirror arm keys from arm_r to arm_l (flip Y and Z rotation)."""
    return [(t, (e[0], -e[1], -e[2])) for t, e in keys]


