def sample(clip, t):
    """Linear Euler sample of a clip at time t -> {bone: euler} (for preview renders only)."""
    pose = {}
    for b, tr in clip['tracks'].items():
        keys = tr.get('r')
        if not keys:
            continue
        if t <= keys[0][0]:
            pose[b] = keys[0][1]; continue
        for (t0, e0), (t1, e1) in zip(keys, keys[1:]):
            if t0 <= t <= t1:
                f = (t - t0) / max(t1 - t0, 1e-9)
                pose[b] = tuple(a + (c - a) * f for a, c in zip(e0, e1)); break
        else:
            pose[b] = keys[-1][1]
    return pose
